const mongoose = require('mongoose');

const ReminderSchema = new mongoose.Schema({
  // pet is optional because appointment-generated reminders may only carry a name
  pet: { type: mongoose.Schema.Types.ObjectId, ref: 'Pet' },
  petName: { type: String, default: '' },
  title: { type: String, required: true },   // e.g. "Rabies Booster"
  dueDate: { type: String, required: true },
  time: { type: String, default: '' },
  clinic: { type: String, default: '' },
  category: { type: String, default: 'Vaccination' }, // Vaccination | Deworming | Flea & Tick | Medication | Checkup | Nutrition | Grooming | Appointment
  status: { type: String, default: 'Upcoming' }, // Upcoming | Overdue | Done
  read: { type: Boolean, default: false }, // toggled by "Mark all read" on the Reminders page

  // Set when the reminder was generated by an approved appointment
  appointment: { type: mongoose.Schema.Types.ObjectId, ref: 'Appointment', default: null },
  source: { type: String, default: 'Manual' }, // Manual | Appointment | Follow-up

  // Follow-up reminders created automatically from a medical record (one per record)
  record: { type: mongoose.Schema.Types.ObjectId, ref: 'MedicalRecord', default: null },

  // Email reminders already sent (so each one goes out once)
  notified3d: { type: Boolean, default: false },
  notifiedDue: { type: Boolean, default: false },

  completedAt: { type: Date, default: null }
}, { timestamps: true });

module.exports = mongoose.model('Reminder', ReminderSchema);
